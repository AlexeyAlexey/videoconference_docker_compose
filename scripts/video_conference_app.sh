#!/usr/bin/env bash

set -euo pipefail
cd "$(dirname "$0")/.."

VIDEO_CONFERENCE_APP_SECRET_KEY_TO_ENCRYPT_PRIVATE_KEY="$(openssl rand -hex 32)"


if [[ -f .env ]] && grep -q '^VIDEO_CONFERENCE_APP_SECRET_KEY_TO_ENCRYPT_PRIVATE_KEY=' .env; then
  sed -i "s/^VIDEO_CONFERENCE_APP_SECRET_KEY_TO_ENCRYPT_PRIVATE_KEY=.*/VIDEO_CONFERENCE_APP_SECRET_KEY_TO_ENCRYPT_PRIVATE_KEY=$VIDEO_CONFERENCE_APP_SECRET_KEY_TO_ENCRYPT_PRIVATE_KEY/" .env
else
  echo "VIDEO_CONFERENCE_APP_SECRET_KEY_TO_ENCRYPT_PRIVATE_KEY=$VIDEO_CONFERENCE_APP_SECRET_KEY_TO_ENCRYPT_PRIVATE_KEY" >> .env
fi

VIDEO_CONFERENCE_APP_SECRET_KEY_BASE="$(openssl rand -hex 32)"


if [[ -f .env ]] && grep -q '^VIDEO_CONFERENCE_APP_SECRET_KEY_BASE=' .env; then
  sed -i "s/^VIDEO_CONFERENCE_APP_SECRET_KEY_BASE=.*/VIDEO_CONFERENCE_APP_SECRET_KEY_BASE=$VIDEO_CONFERENCE_APP_SECRET_KEY_BASE/" .env
else
  echo "VIDEO_CONFERENCE_APP_SECRET_KEY_BASE=$VIDEO_CONFERENCE_APP_SECRET_KEY_BASE" >> .env
fi